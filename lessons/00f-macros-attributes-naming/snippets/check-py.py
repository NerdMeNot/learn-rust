n, pi, name = 42, 3.14159, "Ada"
assert f"{n:5}" == "   42"
assert f"{n:<5}" == "42   "
assert f"{n:05}" == "00042"
assert f"{n:+}" == "+42"
assert f"{pi:.2f}" == "3.14"
assert f"{pi:8.3f}" == "   3.142"
assert f"{255:x}" == "ff"
assert f"{255:#x}" == "0xff"
assert f"{name:>10}" == "       Ada"
assert f"{name:10}" == "Ada       "
assert f"{'Lovelace':.3}" == "Lov"
assert f"{n} {name}" == "42 Ada"
assert f"{{}}" == "{}"
print("ok")
